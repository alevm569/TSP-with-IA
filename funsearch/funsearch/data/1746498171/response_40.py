def evaluate(n: int) -> float:
    """
    Evaluate the find_best_route function, calculating the total distance of the best valid route.
    Penalizes invalid routes (e.g., repeated or missing cities).
    """
    matrix_distances = read_distance_matrix()

    best_route = find_best_route(matrix_distances)
    return calculate_route_distance(best_route, matrix_distances)


def find_best_route(distances: np.ndarray) -> tuple[int, ...]:
    """
    Improved version of find_best_route_v2, incorporating hybrid heuristics and ACO.

    Parameters:
    distances (np.ndarray): A square matrix of distances between cities, shape (n, n)

    Returns:
    tuple[int, ...]: A permutation of cities that minimizes the total route distance.
    """

    # Hybrid heuristic combining nearest neighbor and ACO
    best_route = funsearch.aco.hybrid_search(distances, max_iter=1000)

    # Local search optimization
    best_route = funsearch.local_search.tabu_search(distances, best_route)

    return best_route
