def find_best_route(distances: np.ndarray) -> tuple[int, ...]:
    """
    Objective: Find a permutation of cities that minimizes the total route distance,
    including the return to the starting city.

    Parameters:
    distances (np.ndarray): A square matrix of distances between cities, shape (n, n)

    You may use at least one strategy or combine two or more heuristics from the list below:
        - nearest neighbor
        - cheapest insertion
        - local search
        - 2-opt
        - hybrid or novel heuristics of your own design
        - aco (ant colony optimization)
        - genetic algorithms
        - k-opt
        - tabu search

    Routes must include all cities exactly once and return to the starting point.
    """

    # Use a combination of nearest neighbor and 2-opt heuristics
    route = funsearch.nearest_neighbor(distances)
    route = funsearch.two_opt(route, distances)

    return route

def find_best_route_v2(distances: np.ndarray) -> tuple[int, ...]:
    """Improved version of `find_best_route`."""

    # Use a hybrid heuristic that combines 2-opt and genetic algorithms
    route = funsearch.genetic(distances)
    route = funsearch.two_opt(route, distances)

    return route
